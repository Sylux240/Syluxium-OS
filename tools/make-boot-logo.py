#!/usr/bin/env python3
"""The boot splash logo: Syluxium's mark cut out of the default wallpaper
(bright cyan strokes and the white SYLUXIUM OS lettering, on black), as a
C++ array of 0xRRGGBB pixels compiled into the kernel.
Usage: make-boot-logo.py <wallpaper.png> <out.cpp>"""
import sys
from PIL import Image

# Usage: make-boot-logo.py <wallpaper.png> <out.cpp> [limine-background.png]
src, out = sys.argv[1], sys.argv[2]
PAD = 360  # black below the logo in the Limine background (menu and load bar go there)
im = Image.open(src).convert("RGB")
W, H = im.size
c = im.crop((int(W * 0.672), int(H * 0.11), int(W * 0.895), int(H * 0.53)))
w, h = c.size
px = c.load()
key = Image.new("RGB", (w, h))
kp = key.load()
for y in range(h):
    for x in range(w):
        r, g, b = px[x, y]
        cyan = (min(g, b) - max(110, r * 0.75)) * 2.2  # the mark's cyan strokes, "OS"
        white = (min(r, g, b) - 150) * 3                # white lettering (not the purple clouds)
        a = max(cyan, white) if y > h * 0.76 else cyan
        a = max(0, min(255, int(a)))
        if a < 40:
            a = 0
        kp[x, y] = (r * a // 255, g * a // 255, b * a // 255)
bbox = key.getbbox()
key = key.crop(bbox)
key = key.resize((key.width * 3 // 4, key.height * 3 // 4), Image.LANCZOS)
w, h = key.size
data = list(key.get_flattened_data()) if hasattr(key, "get_flattened_data") else list(key.getdata())
with open(out, "w") as f:
    f.write("// Generated by tools/make-boot-logo.py from the default wallpaper.\n")
    f.write("#include <video/splash.hpp>\nnamespace splash {\n")
    f.write(f"const u32 LOGO_W = {w}, LOGO_H = {h}, LOGO_PAD = {PAD};\nconst u32 LOGO[] = {{\n")
    for i in range(0, len(data), 12):
        f.write(",".join(f"0x{r:02x}{g:02x}{b:02x}" for r, g, b in data[i:i + 12]) + ",\n")
    f.write("};\n}\n")
if len(sys.argv) > 3:
    # Limine draws this centered on black from the moment an entry is picked;
    # the kernel's splash puts the logo at exactly the same place.
    bg = Image.new("RGB", (w, h + PAD))
    bg.paste(key, (0, 0))
    bg.save(sys.argv[3])
print(f"logo {w}x{h}")
