#!/usr/bin/env python3
"""The boot splash picture (Dusk theme): the Syluxium logo with a few faint
stars on deep navy (#0B0F26), with room under the logo for the kernel's
progress bar and status line. Written twice:
  - as a C++ array of 0xRRGGBB pixels compiled into the kernel, and
  - as Limine's wallpaper, which Limine centers on the same navy (backdrop)
    from the moment an entry is picked; the kernel draws the same picture
    at the same place, so the hand-over can't be seen.
Usage: make-boot-logo.py <logo-word.png> <out.cpp> [limine-splash.png]"""
import random
import sys

from PIL import Image, ImageDraw

NAVY = (11, 15, 38)
W, H = 720, 540          # the picture (centered on the screen)
LOGO_H = 280             # logo height (as in the design: 196 x 280)
BAR_W, BAR_H = 280, 4    # progress bar, drawn by the kernel
GAP_LOGO_BAR, GAP_BAR_TEXT = 36, 14
TEXT_H = 16

src, out = sys.argv[1], sys.argv[2]
logo = Image.open(src).convert("RGBA")
logo = logo.resize((round(logo.width * LOGO_H / logo.height), LOGO_H), Image.LANCZOS)
block = LOGO_H + GAP_LOGO_BAR + BAR_H + GAP_BAR_TEXT + TEXT_H
top = (H - block) // 2 - 20  # a little above the middle
bar_y = top + LOGO_H + GAP_LOGO_BAR
text_y = bar_y + BAR_H + GAP_BAR_TEXT

im = Image.new("RGBA", (W, H), NAVY + (255,))
g = ImageDraw.Draw(im)
rnd = random.Random(7)  # the same stars every build
for _ in range(26):
    x, y = rnd.randrange(8, W - 8), rnd.randrange(8, H - 8)
    if abs(x - W // 2) < 130 and top - 10 < y < text_y + 30:
        continue  # not over the logo, bar or text
    a = rnd.uniform(0.25, 0.75)
    c = tuple(int(NAVY[i] + ((223, 230, 255)[i] - NAVY[i]) * a) for i in range(3))
    g.point((x, y), fill=c + (255,))
    if a > 0.65:  # a few brighter ones, 2 px
        g.point((x + 1, y), fill=c + (255,))
im.alpha_composite(logo, ((W - logo.width) // 2, top))
rgb = im.convert("RGB")

data = list(rgb.get_flattened_data()) if hasattr(rgb, "get_flattened_data") else list(rgb.getdata())
with open(out, "w") as f:
    f.write("// Generated by tools/make-boot-logo.py (the Dusk boot splash picture).\n")
    f.write("#include <video/splash.hpp>\nnamespace splash {\n")
    f.write(f"const u32 PIC_W = {W}, PIC_H = {H}, PIC_BG = 0x{NAVY[0]:02x}{NAVY[1]:02x}{NAVY[2]:02x};\n")
    f.write(f"const u32 PIC_BAR_W = {BAR_W}, PIC_BAR_H = {BAR_H}, PIC_BAR_Y = {bar_y}, PIC_TEXT_Y = {text_y};\n")
    f.write("const u32 PIC[] = {\n")
    for i in range(0, len(data), 12):
        f.write(",".join(f"0x{r:02x}{g_:02x}{b:02x}" for r, g_, b in data[i:i + 12]) + ",\n")
    f.write("};\n}\n")
if len(sys.argv) > 3:
    rgb.save(sys.argv[3])
print(f"splash picture {W}x{H}, bar at y={bar_y}")
