#!/usr/bin/env python3
"""Convert a PSF2 console font (8 px wide) into a C++ glyph table.

Usage: psf2cpp.py <font.psf[u][.gz]> <output.cpp>

The output holds 256 glyphs indexed by Unicode code point U+0000..U+00FF
(ASCII + Latin-1), looked up via the font's Unicode table.
"""
import gzip
import struct
import sys

PSF2_MAGIC = 0x864AB572
PSF2_HAS_UNICODE_TABLE = 0x01


def main() -> None:
    src, dst = sys.argv[1], sys.argv[2]
    opener = gzip.open if src.endswith(".gz") else open
    with opener(src, "rb") as f:
        data = f.read()

    magic, _version, header_size, flags, num_glyphs, bytes_per_glyph, height, width = struct.unpack_from("<8I", data)
    if magic != PSF2_MAGIC:
        sys.exit("not a PSF2 font")
    if width != 8:
        sys.exit(f"only 8-pixel-wide fonts are supported (got {width})")

    glyphs_end = header_size + num_glyphs * bytes_per_glyph
    glyph = lambda i: data[header_size + i * bytes_per_glyph: header_size + (i + 1) * bytes_per_glyph]

    mapping: dict[int, int] = {}
    if flags & PSF2_HAS_UNICODE_TABLE:
        table = data[glyphs_end:]
        pos = 0
        for g in range(num_glyphs):
            end = table.index(b"\xff", pos)
            singles = table[pos:end].split(b"\xfe")[0]  # ignore multi-codepoint sequences
            for ch in singles.decode("utf-8"):
                mapping.setdefault(ord(ch), g)
            pos = end + 1
    else:
        mapping = {i: i for i in range(min(256, num_glyphs))}

    fallback = mapping.get(ord("?"), 0)
    blank = bytes(bytes_per_glyph)

    lines = [
        "// Generated by tools/psf2cpp.py -- do not edit.",
        "//",
        "// Terminus Font, Copyright (c) Dimitar Toshkov Zhekov.",
        "// Licensed under the SIL Open Font License, Version 1.1.",
        "",
        "#include <video/font.hpp>",
        "",
        "namespace video {",
        "",
        f"static const u8 glyph_data[][{height}] = {{",
    ]
    for cp in range(256):
        if cp in mapping:
            g = glyph(mapping[cp])
        elif cp < 0x20 or 0x7F <= cp < 0xA0:
            g = blank
        else:
            g = glyph(fallback)
        # Quote the label: a comment ending in '\' would splice the next line into it.
        label = f"'{chr(cp)}'" if 0x20 <= cp < 0x7F else ""
        hexes = ", ".join(f"0x{b:02x}" for b in g)
        lines.append(f"    {{{hexes}}}, // U+{cp:04X} {label}".rstrip())
    lines += [
        "};",
        "static_assert(sizeof(glyph_data) / sizeof(glyph_data[0]) == 256, \"glyph table must have 256 entries\");",
        "",
        f"const Font default_font = {{{width}, {height}, &glyph_data[0][0]}};",
        "",
        "} // namespace video",
        "",
    ]
    with open(dst, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
